// Generative AI analyst: grounded research briefs and a chat interface backed by
// Cloudflare Workers AI. The provider/model are resolved by the Worker; this
// view never holds an API key.

import {
  UNIVERSE, state, $, escapeHtml, formatPercent, dateShort, toast, sourceLabel,
} from './shared.js';
import { live, aiAnalysis, aiChat, aiStatus } from '../core/live.js';

const SUGGESTIONS = [
  'What are the biggest risks in this setup?',
  'Explain the recent price action without hype.',
  'What would invalidate the thesis?',
  'How does the macro backdrop affect this asset?',
  'Compare this asset with SPY on risk and momentum.',
];

const aiState = {
  symbol: state.research?.symbol ?? 'SPY',
  messages: [],
  analysis: null,
  meta: null,
  busy: false,
  statusAttempted: false,
  statusBusy: false,
  statusError: null,
};

let initialized = false;

function available() {
  return live.enabled && live.ai?.enabled !== false;
}

function shortModel(model) {
  const value = String(model ?? '');
  if (value.includes('llama-3.3-70b')) return 'Llama 3.3 70B';
  if (value.includes('llama-3.1-8b')) return 'Llama 3.1 8B';
  if (value.includes('qwen3-30b')) return 'Qwen 3 30B';
  return value.split('/').pop() || 'Workers AI';
}

function formatText(value) {
  return escapeHtml(String(value ?? '')).replace(/\n/g, '<br>');
}

function section(label, value) {
  if (!value) return '';
  return `<div class="ai-analysis-section"><span>${escapeHtml(label)}</span><p>${formatText(value)}</p></div>`;
}

function list(label, values) {
  const items = Array.isArray(values) ? values.filter(Boolean) : [];
  if (!items.length) return '';
  return `<div class="ai-analysis-section"><span>${escapeHtml(label)}</span><ul>${items.map((item) => `<li>${formatText(item)}</li>`).join('')}</ul></div>`;
}

function renderAnalysis() {
  const target = $('#ai-analysis');
  if (!target) return;
  if (!live.enabled) {
    target.innerHTML = `
      <div class="ai-empty">
        <strong>AI Analyst needs the Cloudflare Workers deployment.</strong>
        <p>The static GitHub Pages build keeps the deterministic local engine. The live Worker exposes
        <code>/api/ai/chat</code> and <code>/api/ai/analysis/:symbol</code> through the free Workers AI binding.</p>
        <p class="muted small">Open the Worker URL to use generative analysis and chat.</p>
      </div>`;
    return;
  }
  if (live.ai?.enabled === false) {
    target.innerHTML = `
      <div class="ai-empty">
        <strong>The Worker is live but the AI binding is not configured.</strong>
        <p>Add <code>"ai": { "binding": "AI" }</code> to <code>worker/wrangler.jsonc</code> and redeploy.</p>
      </div>`;
    return;
  }
  if (!aiState.analysis) {
    target.innerHTML = `
      <div class="ai-empty">
        <strong>Generate a grounded research brief.</strong>
        <p>Pick an asset and ask the model for a structured view. The prompt includes live quote, performance,
        volatility, fundamentals, macro, sentiment, news and data-quality context from the Worker.</p>
        <p class="muted small">Provider: Cloudflare Workers AI · model fallback enabled · free daily allocation.</p>
      </div>`;
    return;
  }
  const a = aiState.analysis;
  const meta = aiState.meta ?? {};
  const stanceClass = a.stance === 'bullish' ? 'good' : a.stance === 'bearish' ? 'danger' : 'warn';
  target.innerHTML = `
    <div class="ai-analysis-head">
      <span class="pill ${stanceClass}">${escapeHtml(a.stance)}</span>
      <span class="muted">Confidence ${formatPercent(a.confidence, 0)}</span>
      <span class="muted">${escapeHtml(sourceLabel(meta.source ?? 'server'))} · ${dateShort(meta.generatedAt)}</span>
    </div>
    <h3>${formatText(a.summary)}</h3>
    <div class="ai-analysis-grid">
      ${section('Technical', a.technical)}
      ${section('Fundamental', a.fundamental)}
      ${section('Macro', a.macro)}
      ${section('Sentiment', a.sentiment)}
    </div>
    <div class="ai-analysis-columns">
      ${list('Catalysts', a.catalysts)}
      ${list('Risks', a.risks)}
      ${list('Action plan', a.actionPlan)}
    </div>
    <p class="muted small ai-disclaimer">${formatText(a.disclaimer)}</p>
    <p class="muted small">Generated by ${escapeHtml(meta.provider ?? live.ai?.provider ?? 'Cloudflare Workers AI')} · ${escapeHtml(shortModel(meta.model ?? live.ai?.model))} · source ${escapeHtml(sourceLabel(meta.source ?? 'server'))}.</p>`;
}

function renderChat() {
  const target = $('#ai-chat');
  if (!target) return;
  const messages = aiState.messages.length
    ? aiState.messages
    : [{
      role: 'assistant',
      content: available()
        ? `Ask me about ${aiState.symbol}, macro conditions, portfolio risk or the research process. I use the selected asset's Worker context and will say when the data is incomplete.`
        : 'The AI chat is available on the Cloudflare Workers deployment. The static build stays deterministic and offline-first.',
    }];
  target.innerHTML = messages.map((message) => `
    <div class="ai-message ${message.role === 'user' ? 'user' : 'assistant'}">
      <span class="ai-message-role">${message.role === 'user' ? 'You' : 'InvestorKit AI'}</span>
      <p>${formatText(message.content)}</p>
    </div>`).join('') + (aiState.busy ? `
    <div class="ai-message assistant ai-thinking">
      <span class="ai-message-role">InvestorKit AI</span>
      <p>Thinking through the supplied context…</p>
    </div>` : '');
  target.scrollTop = target.scrollHeight;
}

function renderStatus() {
  const pill = $('#ai-status-pill');
  const badge = $('#ai-model-badge');
  const ok = available();
  if (pill) {
    pill.textContent = !live.enabled ? 'Worker required' : ok ? 'Generative · online' : 'AI binding missing';
    pill.className = `pill ${ok ? 'good' : 'warn'}`;
  }
  if (badge) {
    badge.textContent = ok
      ? shortModel(live.ai?.models?.primary ?? live.ai?.model)
      : 'Not connected';
    badge.title = live.ai?.models?.primary ?? '';
  }
  for (const selector of ['#ai-generate', '#ai-send', '#ai-input']) {
    const element = $(selector);
    if (element) element.disabled = !ok || aiState.busy;
  }
  const generate = $('#ai-generate');
  if (generate) generate.classList.toggle('is-busy', aiState.busy && !aiState.analysis);
  const send = $('#ai-send');
  if (send) send.classList.toggle('is-busy', aiState.busy);
}

export function renderAI() {
  const panel = $('#tab-ai');
  if (!panel) return;
  if (live.enabled && !aiState.statusAttempted && !aiState.statusBusy) {
    aiState.statusAttempted = true;
    aiState.statusBusy = true;
    aiStatus()
      .then((status) => {
        live.ai = status;
        aiState.statusError = null;
      })
      .catch((error) => {
        aiState.statusError = error?.message ?? 'AI status unavailable';
      })
      .finally(() => {
        aiState.statusBusy = false;
        renderStatus();
        renderAnalysis();
        renderChat();
      });
  }
  renderStatus();
  renderAnalysis();
  renderChat();
}

async function generate() {
  if (!available() || aiState.busy) return;
  aiState.busy = true;
  aiState.analysis = null;
  aiState.meta = null;
  renderAI();
  try {
    const payload = await aiAnalysis(aiState.symbol);
    aiState.analysis = payload.analysis;
    aiState.meta = payload;
    live.ai = {
      ...(live.ai ?? {}),
      enabled: true,
      provider: payload.provider,
      model: payload.model,
      models: { ...(live.ai?.models ?? {}), primary: payload.model },
    };
    toast(`AI brief generated for ${aiState.symbol}`);
  } catch (error) {
    toast(`AI analysis failed: ${error?.message ?? 'unknown error'}`);
  } finally {
    aiState.busy = false;
    renderAI();
  }
}

async function send() {
  if (!available() || aiState.busy) return;
  const input = $('#ai-input');
  const text = input?.value.trim();
  if (!text) return;
  aiState.messages.push({ role: 'user', content: text });
  if (input) input.value = '';
  aiState.busy = true;
  renderAI();
  try {
    const payload = await aiChat(aiState.messages.slice(-12), { symbol: aiState.symbol });
    aiState.messages.push({ role: 'assistant', content: payload.reply });
    if (payload.model) {
      live.ai = {
        ...(live.ai ?? {}),
        enabled: true,
        provider: payload.provider,
        model: payload.model,
      };
    }
  } catch (error) {
    aiState.messages.push({
      role: 'assistant',
      content: `I could not reach the AI provider: ${error?.message ?? 'unknown error'}. Check the Worker AI binding and the free-tier quota, then try again.`,
    });
    toast(`AI chat failed: ${error?.message ?? 'unknown error'}`);
  } finally {
    aiState.busy = false;
    renderAI();
  }
}

export function initAI() {
  if (initialized) return;
  const select = $('#ai-symbol');
  if (!select) return;
  select.innerHTML = UNIVERSE
    .map((asset) => `<option value="${asset.symbol}">${asset.symbol} · ${escapeHtml(asset.name)}</option>`)
    .join('');
  select.value = aiState.symbol;
  select.addEventListener('change', () => {
    aiState.symbol = select.value;
    aiState.analysis = null;
    aiState.meta = null;
    aiState.messages = [];
    renderAI();
  });
  $('#ai-generate')?.addEventListener('click', generate);
  $('#ai-clear')?.addEventListener('click', () => {
    aiState.messages = [];
    aiState.analysis = null;
    aiState.meta = null;
    renderAI();
  });
  $('#ai-chat-form')?.addEventListener('submit', (event) => {
    event.preventDefault();
    send();
  });
  $('#ai-input')?.addEventListener('keydown', (event) => {
    if (event.key === 'Enter' && !event.shiftKey) {
      event.preventDefault();
      send();
    }
  });
  const suggestions = $('#ai-suggestions');
  if (suggestions) {
    suggestions.innerHTML = SUGGESTIONS
      .map((prompt) => `<button type="button" class="ai-suggestion" data-ai-prompt="${escapeHtml(prompt)}">${escapeHtml(prompt)}</button>`)
      .join('');
    suggestions.addEventListener('click', (event) => {
      const button = event.target.closest('[data-ai-prompt]');
      if (!button || !available() || aiState.busy) return;
      const input = $('#ai-input');
      if (input) input.value = button.dataset.aiPrompt ?? '';
      send();
    });
  }
  document.addEventListener('ik:market-updated', () => {
    if (live.ai?.models) aiState.statusAttempted = true;
    renderAI();
  });
  if (live.ai?.models) aiState.statusAttempted = true;
  initialized = true;
  renderAI();
}
